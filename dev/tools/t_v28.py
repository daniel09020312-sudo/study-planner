def openat(when,w=390,h=844,scheme='light'):
    ctx=R.browser.new_context(viewport={'width':w,'height':h},device_scale_factor=2,color_scheme=scheme,timezone_id='Asia/Seoul',reduced_motion='reduce')
    ctx.clock.set_system_time(when)
    ctx.route(re.compile(r'^https?://'),route)
    pg=ctx.new_page()
    pg.on('pageerror',lambda e:R.errors.append('pageerror: '+str(e)))
    pg.on('console',lambda m:R.errors.append('console: '+m.text) if m.type=='error' and 'net::ERR' not in m.text else None)
    pg.add_init_script("try{localStorage.setItem('gbb_me','m1');localStorage.setItem('gbb_note','9999999999999');localStorage.setItem('gbb_pinask',JSON.stringify({m1:1,m2:1,m3:1}));}catch(e){}")
    pg.add_init_script(MOCK)
    pg.goto(PAGE);pg.wait_for_timeout(1600)
    for _ in range(3):close_dlg(pg)
    return pg
def ev(p,js):return p.evaluate('()=>'+js)
